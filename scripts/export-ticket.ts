// Writes a ticket signed by the TypeScript verifier (DEMO key) so the Rust
// contract tests can prove the two sides interoperate byte-for-byte.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DEMO_KEYS } from "../src/keys.ts";
import { ROOT } from "../src/util.ts";

const mk = (verdict: string, nonce: number) => JSON.stringify({
  v: 1, verdict, vault: "vault.jev.testnet", agent: "agent.testnet", receiver: "shop.testnet",
  amount: (10n ** 24n).toString(), nonce, expires_at_ms: 1_800_000_000_000 + 60_000, evidence: "ab".repeat(32),
});
const v = DEMO_KEYS.verifier(), h = DEMO_KEYS.human();
const allow = mk("allow", 1), warn = mk("warn", 2);
const out = {
  _note: "Generated by scripts/export-ticket.ts with DEMO keys. Used by contract/src/tests.rs.",
  verifier_pk: v.publicKeyHex, human_pk: h.publicKeyHex,
  allow: { ticket: allow, verifier_sig: v.sign(allow) },
  warn: { ticket: warn, verifier_sig: v.sign(warn), human_sig: h.sign(warn) },
};
writeFileSync(resolve(ROOT, "contract/src/fixtures/ts_tickets.json"), JSON.stringify(out, null, 2) + "\n");
console.log("wrote contract/src/fixtures/ts_tickets.json");
